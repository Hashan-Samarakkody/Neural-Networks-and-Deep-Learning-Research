"""Regenerate the numeric sections of README.md from outputs/results/paper_numbers.json."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent


def f2(x):
    return f"{float(x):.2f}"


def main(results_dir: Path = ROOT / "outputs" / "results", readme: Path = ROOT.parent / "README.md") -> None:
    pn = json.loads((results_dir / "paper_numbers.json").read_text())
    ef, ex = pn["event_flow"], pn["paper_extras"]
    td = pn["target_distribution"]
    allx = pn["all_experiments"]

    def best(exp, models=("XGBoost", "RandomForest", "SVR", "Ridge", "TwoStage")):
        rows = [r for r in allx[exp] if r["Model"] in models]
        rows.sort(key=lambda r: r["MAE"])
        return rows

    def mae(exp, m):
        return next(r["MAE"] for r in allx[exp] if r["Model"] == m)

    A, B = best("ExpA_LOOCV"), best("ExpB_Chronological")
    tests = {t["model_b"]: t for t in pn["permutation_tests"]}
    surv = {(r["experiment"], r["model"]): r for r in pn["survival"]}
    man = pn["run_manifest"]
    perm = pn["permutation_importance_ExpA"]
    experiments = (
        "## Experiments\n\n| Experiment | Dataset | Validation | N (events) |\n|------------|---------|------------|------------|\n"
        f"| A | Physical disasters outside 2019–2022 | LOOCV; 12-month buffered LOOCV; leave-one-year-out; expanding window | {ef['exp_A_N']} |\n"
        f"| B | All events including 2019–2022 | Chronological split (train ≤ 2018, test ≥ 2019) | {ef['exp_B_N']} ({ef['exp_B_train_N']} train / {ef['exp_B_test_N']} test) |\n\n"
    )
    findings = (
        "## Key Findings\n\n> Generated by `src/make_readme.py` from `pipeline/outputs/results/paper_numbers.json`; "
        f"run at commit `{man['commit'][:7]}` with pinned versions: {man.get('pinned_versions_ok')}.\n\n"
        f"- **Sample:** {ef['raw_emdat_records']} raw EM-DAT records → {ef['physical_disasters_before_cluster']} physical → "
        f"{ef['physical_disasters_after_cluster']} after clustering → {ef['events_valid_target']} with a valid target.\n"
        f"- **Target:** {td['n_zero_months']} of {td['n_total']} events have T_rec = 0; mean {td['mean']} months; "
        f"{td['n_right_censored_12']} right-censored at 12 months, all in 2019–2022 ({ex['crisis_window']['n_censored']} of {ex['crisis_window']['n']}).\n"
        f"- **Experiment A (LOOCV, N={ef['exp_A_N']}):** best {A[0]['Model']} (MAE {f2(A[0]['MAE'])}), then {A[1]['Model']} ({f2(A[1]['MAE'])}); "
        f"predicting zero gives {f2(ex['expA']['predict_zero_MAE'])}. Under 12-month buffered LOOCV the best MAE is "
        f"{f2(best('ExpA_BufferedLOOCV')[0]['MAE'])} ({best('ExpA_BufferedLOOCV')[0]['Model']}).\n"
        f"- **Experiment B (chronological, N={ef['exp_B_test_N']} test):** best {B[0]['Model']} (MAE {f2(B[0]['MAE'])}).\n"
        f"- **Tests (sign-flip permutation, Holm):** XGBoost vs NaiveMean p_holm {tests['NaiveMean']['p_holm']}; vs NaiveMedian p_holm {tests['NaiveMedian']['p_holm']}.\n"
        f"- **Survival (Experiment B C-index):** CoxPH {surv[('ExpB_Chronological','CoxPH')]['c_index']}, "
        f"RandomSurvivalForest {surv[('ExpB_Chronological','RandomSurvivalForest')]['c_index']}, "
        f"DiscreteHazard {surv[('ExpB_Chronological','DiscreteHazard')]['c_index']} (`survival_results.csv`).\n"
        f"- **Permutation importance (Experiment A):** {perm[0]['Feature']} ({perm[0]['mean_mae_increase']} months MAE increase).\n\n"
    )
    limits = (
        "## Known Limitations\n\n"
        "1. **Target validity:** non-zero targets coincide with national shocks (2007–2009, 2023) and all censored events fall in 2020–2022; "
        "see `confounding_sensitivity.csv`.\n"
        f"2. **Zero-inflation:** {td['n_zero_months']} of {td['n_total']} targets are zero; the two-stage model was added post hoc with fixed C=1, α=1.\n"
        "3. **Dependence:** events are closely spaced; buffered and leave-one-year-out results are the primary evidence, plain LOOCV is optimistic.\n"
        "4. **Version sensitivity:** XGBoost results depend on library versions; see `docs/VERSION_SENSITIVITY.md`. Run only in the pinned environment.\n"
        "5. **Static DTII** shares and annual macro values (2024–2025 are projections).\n"
    )
    txt = readme.read_text()
    txt = re.sub(r"## Experiments\n.*?(?=## Key Findings)", lambda m: experiments, txt, flags=re.S)
    txt = re.sub(r"## Key Findings\n.*?(?=## Configuration)", lambda m: findings, txt, flags=re.S)
    txt = re.sub(r"## Known Limitations\n.*\Z", lambda m: limits, txt, flags=re.S)
    readme.write_text(txt)
    print("README.md regenerated from paper_numbers.json")


if __name__ == "__main__":
    main()
